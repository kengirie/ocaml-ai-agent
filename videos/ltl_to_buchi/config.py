def plain(say):
    return say.replace("|", "")


def cue_prefixes(say):
    """各キューの直前までの文字列（最初のキュー=0 は空文字）。"""
    parts = say.split("|")
    return ["".join(parts[:i]) for i in range(len(parts))]
